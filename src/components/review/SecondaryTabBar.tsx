export default function SecondaryTabBar({ activeTab, onTabChange, showPreviewTab = true }: SecondaryTabBarProps) {
  const visibleTabs = showPreviewTab ? TABS : TABS.filter(t => !t.previewOnly);

  return (
    <div className="flex items-center gap-1 border-b border-gray-200 bg-white rounded-t-xl px-2">
      {visibleTabs.map((tab) => {
        const isActive = activeTab === tab.id;
        return (
          <button
            key={tab.id}
            onClick={() => onTabChange(tab.id)}
            className={`flex items-center gap-2 px-4 py-3 text-sm font-medium transition-colors border-b-2 -mb-px ${
              isActive
                ? "text-brand-blue border-brand-blue"
                : "text-gray-500 border-transparent hover:text-gray-700 hover:border-gray-300"
            }`}
          >
            {tab.icon}
            <span>{tab.label}</span>
          </button>
        );
      })}
    </div>
  );
}
